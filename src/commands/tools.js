/**
 * Category A: Photoshop Tools
 * All tools use verified Action Manager tool class names via batchPlay.
 */
'use strict';

function makeToolCommand({ id, name, subcategory, toolClass, description, keywords, aliases, shortcut }) {
  return {
    id,
    name,
    category: 'Tools',
    subcategory: subcategory || 'TOOL',
    description,
    keywords,
    aliases: aliases || [],
    shortcut: shortcut || null,
    requiresDocument: false,
    requiresLayer: false,
    requiresUnlockedLayer: false,
    destructive: false,
    handler: async ({ selectTool }) => selectTool(toolClass, name),
  };
}

