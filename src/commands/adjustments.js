/**
 * Category C: Adjustments
 * Creates non-destructive Adjustment Layers via batchPlay so edits remain
 * fully reversible with layer masks and standard Photoshop Undo.
 */
'use strict';

function makeAdjustmentCommand({ id, name, subcategory, adjustmentObj, extraProps, description, keywords, aliases }) {
  return {
    id,
    name,
    category: 'Adjustments',
    subcategory: subcategory || 'ADJUSTMENT LAYER',
    description,
    keywords,
    aliases: aliases || [],
    requiresDocument: true,
    requiresLayer: false,
    requiresUnlockedLayer: false,
    unsupportedColorModes: ['bitmap', 'indexed'],
    destructive: false,
    handler: async ({ createAdjustmentLayer }) =>
      createAdjustmentLayer(adjustmentObj, `Add ${name} Adjustment Layer`, extraProps || {}),
  };
}

